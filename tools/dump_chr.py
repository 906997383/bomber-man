def decode_tile(off):
    px = [[0]*8 for _ in range(8)]
    for y in range(8):
        lo = chr_[off+y]
        hi = chr_[off+8+y]
        for x in range(8):
            bit = 7-x
            v = ((lo>>bit)&1) | (((hi>>bit)&1)<<1)
            px[y][x] = v
    return px

def sheet(out, scale=6):
    W = 16*8*scale
    H = 16*8*scale
    img = Image.new('RGB', (W, H), (0,0,0))
    p = img.load()
    # assign generic colors per 4 tiles? use grayscale palette indices 0x0F,0x00,0x10,0x30
    cols = [pal[0x0F], pal[0x00], pal[0x10], pal[0x30]]
    for t in range(256):
        tx = (t % 16)*8*scale
        ty = (t//16)*8*scale
        px = decode_tile(t*16)
        for y in range(8):
            for x in range(8):
                c = cols[px[y][x]]
                for dy in range(scale):
                    for dx in range(scale):
                        p[tx+x*scale+dx, ty+y*scale+dy] = c
    img.save(out)

